export function createPassport(project, issues, constraints, verifications) {
  const scan = project.scan || JSON.parse(project.summary_json)
  return {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    project: {
      name: project.name,
      source: project.source,
      scannedAt: project.scanned_at,
      language: scan.language,
      framework: scan.framework,
      packageName: scan.packageName,
      packageVersion: scan.packageVersion,
      description: scan.description,
      packageManager: scan.packageManager,
    },
    architecture: {
      detectedConfigs: scan.configs,
      files: scan.files,
      totalScannedFiles: scan.fileCount,
      readmeExcerpt: scan.readme,
    },
    dependencies: scan.dependencies,
    availableCommands: scan.commands,
    toolCompatibility: scan.toolCompatibility || [],
    knownIssues: issues.map((issue) => ({
      title: issue.title,
      details: issue.details,
      status: issue.status,
      createdAt: issue.created_at,
      attempts: issue.attempts.map((attempt) => ({
        description: attempt.description,
        outcome: attempt.outcome,
        createdAt: attempt.created_at,
      })),
    })),
    constraints: constraints.map((constraint) => constraint.content),
    verification: verifications.map((check) => ({
      command: check.command,
      status: check.status,
      output: check.output,
      durationMs: check.duration_ms,
      createdAt: check.created_at,
    })),
  }
}

export function passportMarkdown(passport) {
  const project = passport.project
  const architecture = passport.architecture
  const dependencies = passport.dependencies.length
    ? passport.dependencies.map((dependency) => `- \`${dependency}\``).join('\n')
    : '- No package dependencies detected.'
  const commands = passport.availableCommands.length
    ? passport.availableCommands.map((item) => `- \`${item.command}\``).join('\n')
    : '- No build or test scripts detected.'
  const issues = passport.knownIssues.length
    ? passport.knownIssues.map((issue) => {
      const attempts = issue.attempts.length
        ? issue.attempts.map((attempt) => `  - ${attempt.description} — **${attempt.outcome}**`).join('\n')
        : '  - No repair attempts recorded.'
      return `### ${issue.title} (${issue.status})\n\n${issue.details || 'No details provided.'}\n\n**Repair history**\n${attempts}`
    }).join('\n\n')
    : 'No known issues recorded.'
  const constraints = passport.constraints.length
    ? passport.constraints.map((item) => `- ${item}`).join('\n')
    : '- No project constraints recorded.'
  const verification = passport.verification.length
    ? passport.verification.map((item) => `- **${item.status.toUpperCase()}** \`${item.command}\` — ${new Date(item.createdAt).toLocaleString()}`).join('\n')
    : '- No checks have been run.'
  const compatibility = passport.toolCompatibility.length
    ? passport.toolCompatibility.map((tool) => {
      const status = tool.nativeFiles.length
        ? `Native instructions detected: ${tool.nativeFiles.map((file) => `\`${file}\``).join(', ')}`
        : 'No native instruction file detected; use the portable Markdown or JSON passport.'
      return `- **${tool.name}:** ${status}`
    }).join('\n')
    : '- No editor-specific instruction files were detected.'

  return `# ${project.name} — Project Passport

> Portable engineering context generated ${new Date(passport.generatedAt).toLocaleString()}.

## At a glance
- **Language:** ${project.language}
- **Framework:** ${project.framework}
- **Package:** ${project.packageName}${project.packageVersion ? `@${project.packageVersion}` : ''}
- **Package manager:** ${project.packageManager}
- **Source:** ${project.source}
- **Description:** ${project.description || 'Not provided'}

## Architecture and setup
${architecture.readmeExcerpt ? `### README excerpt\n${architecture.readmeExcerpt}\n\n` : ''}### Detected configuration
${architecture.detectedConfigs.length ? architecture.detectedConfigs.map((name) => `- \`${name}\``).join('\n') : '- No known configuration files detected.'}

### Project files (${architecture.totalScannedFiles} scanned)
${architecture.files.map((file) => `- \`${file}\``).join('\n') || '- No files detected.'}

### Available commands
${commands}

## Dependencies (${passport.dependencies.length})
${dependencies}

## Coding assistant compatibility
ProjectPassport checks for repository instruction files; this is not a live IDE integration test. Every listed tool can receive the exported Markdown or JSON passport. A detected file indicates project-native instructions are present, not that a particular tool version or plugin was tested.

${compatibility}

## Known issues and repair history
${issues}

## Constraints and decisions
${constraints}

## Verification evidence
${verification}

---
Generated by ProjectPassport. Verification commands run project-defined scripts; run them only for projects you trust.
`
}
